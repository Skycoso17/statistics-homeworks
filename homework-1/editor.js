"use strict";
/* Live text editor for the preview only (not part of the GitHub Pages files).
   The owner clicks "Edit texts", rewrites any text on the page, and presses Save.
   Each save is stored as one document in the artifact's db collection "edits",
   so Claude can read it back and apply it to index.html / app.js. */
(() => {
  const CANDIDATES = "h1,h2,h3,h4,p,li,figcaption,td,th,dt,dd,summary,.eyebrow,.num,.guide-tag,.meta,.meta-line,.note,.mini,.lede,.brand,.strip-label,.stat-method,label";
  const SKIP_INSIDE = "svg,script,style,select,input,textarea,button,.edit-ui";
  // containers whose text is generated by app.js (an edit there is applied in the JS templates)
  const DYNAMIC = ["statTrial","simpleDist","statUniform","simpleBits","simpleRelation","simpleAvalanche","simpleConclusion","stepInfo","animInterpretation","rcText","realCurve","ideaInt","ideaEc","cycleStrip","bitStrip","zoomNote","speedLbl"];
  const norm = s => (s || "").replace(/\s+/g, " ").trim();
  let db = null, editing = false, originals = new Map(), pending = [];

  /* ---------- UI ---------- */
  const css = document.createElement("style");
  css.textContent = `
  .edit-ui{position:fixed;right:16px;bottom:calc(16px + env(safe-area-inset-bottom,0px));z-index:50;display:flex;flex-direction:column;align-items:flex-end;gap:8px;font:14px/1.4 system-ui,-apple-system,"Segoe UI",sans-serif}
  .edit-bar{display:flex;gap:8px;align-items:center;flex-wrap:wrap;justify-content:flex-end;background:var(--card);border:1px solid var(--line);border-radius:12px;padding:8px;box-shadow:0 6px 24px rgba(0,0,0,.14)}
  .edit-bar button{font:inherit;font-weight:700;padding:8px 12px;border-radius:8px;border:1px solid var(--line);background:var(--card);color:var(--ink);cursor:pointer}
  .edit-bar button.primary{background:var(--acc);border-color:var(--acc);color:var(--on-acc)}
  .edit-bar button:disabled{opacity:.45;cursor:not-allowed}
  .edit-count{color:var(--mute);font-size:13px;padding:0 4px}
  .edit-toast{background:var(--ink);color:var(--paper);border-radius:10px;padding:10px 14px;max-width:320px;box-shadow:0 6px 24px rgba(0,0,0,.2)}
  body.editing [data-editable]{outline:1px dashed color-mix(in srgb,var(--acc) 55%,transparent);outline-offset:2px;border-radius:3px;cursor:text}
  body.editing [data-editable]:hover{background:color-mix(in srgb,var(--acc) 7%,transparent)}
  body.editing [data-editable]:focus{outline:2px solid var(--acc);background:var(--acc-soft)}
  body.editing [data-editable].changed{outline:2px solid var(--amber,#b8730a)}
  .top body.editing [data-editable]{outline-color:rgba(255,255,255,.5)}
  `;
  document.head.appendChild(css);
  const ui = document.createElement("div"); ui.className = "edit-ui"; ui.hidden = true;
  ui.innerHTML = `<div class="edit-toast" id="editToast" hidden></div>
    <div class="edit-bar">
      <span class="edit-count" id="editCount"></span>
      <button id="editUndo" hidden>Undo changes</button>
      <button id="editSave" class="primary" hidden disabled>Save</button>
      <button id="editToggle">✎ Edit texts</button>
    </div>`;
  document.body.appendChild(ui);
  const $ = id => document.getElementById(id);
  let toastTimer;
  const toast = msg => { const t = $("editToast"); t.textContent = msg; t.hidden = false; clearTimeout(toastTimer); toastTimer = setTimeout(() => (t.hidden = true), 5000); };

  /* ---------- which elements are editable ---------- */
  function editableElements() {
    const out = [];
    document.querySelectorAll(CANDIDATES).forEach(el => {
      if (el.closest(SKIP_INSIDE) || !norm(el.textContent)) return;
      if (out.some(o => o.contains(el))) return;              // an ancestor is already editable
      if (el.querySelector("svg,select,input,button,table,.chart-narrow,figure")) return;
      out.push(el);
    });
    return out;
  }
  function changedList() { return [...originals].filter(([el, o]) => el.isConnected && el.innerHTML !== o.html); }
  function refreshCount() {
    const n = changedList().length;
    originals.forEach((o, el) => el.classList.toggle("changed", el.innerHTML !== o.html));
    $("editCount").textContent = editing ? (n ? `${n} changed` : "Click any text to edit it") : (pending.length ? `${pending.length} saved change${pending.length > 1 ? "s" : ""} waiting for Claude` : "");
    $("editSave").disabled = !n; $("editUndo").hidden = !editing || !n;
  }
  function setEditing(on) {
    editing = on;
    document.body.classList.toggle("editing", on);
    $("editToggle").textContent = on ? "Done" : "✎ Edit texts";
    $("editSave").hidden = !on;
    if (on) {
      originals = new Map();
      editableElements().forEach(el => {
        originals.set(el, { html: el.innerHTML, text: norm(el.textContent) });
        el.setAttribute("data-editable", ""); el.contentEditable = "true"; el.spellcheck = true;
      });
    } else {
      document.querySelectorAll("[data-editable]").forEach(el => { el.removeAttribute("data-editable"); el.removeAttribute("contenteditable"); el.classList.remove("changed"); });
    }
    refreshCount();
  }
  document.addEventListener("input", e => { if (editing && e.target.closest && e.target.closest("[data-editable]")) refreshCount(); });
  document.addEventListener("keydown", e => {
    if (!editing) return;
    if ((e.metaKey || e.ctrlKey) && e.key.toLowerCase() === "s") { e.preventDefault(); save(); }
    if (e.key === "Escape" && document.activeElement && document.activeElement.hasAttribute("data-editable")) document.activeElement.blur();
  });
  // keep links and buttons inert while editing
  document.addEventListener("click", e => { if (editing && e.target.closest("[data-editable] a")) e.preventDefault(); }, true);
  // paste as plain text
  document.addEventListener("paste", e => {
    if (!editing || !e.target.closest || !e.target.closest("[data-editable]")) return;
    e.preventDefault(); document.execCommand("insertText", false, (e.clipboardData || window.clipboardData).getData("text/plain"));
  });

  /* ---------- save / restore ---------- */
  async function save() {
    const list = changedList(); if (!list.length || !db) return;
    const changes = list.map(([el, o]) => {
      const sec = el.closest("section[id]"), dyn = DYNAMIC.find(id => el.closest("#" + id));
      return { section: sec ? sec.id : (el.closest("header") ? "header" : "page"), tag: el.tagName.toLowerCase(),
        before: o.text, beforeHtml: o.html, after: norm(el.textContent), afterHtml: el.innerHTML.trim(), generatedBy: dyn || null };
    });
    $("editSave").disabled = true;
    try {
      await db.collection("edits").add({ status: "pending", savedAt: new Date().toISOString(), changes });
      list.forEach(([el]) => originals.set(el, { html: el.innerHTML, text: norm(el.textContent) }));
      pending.push(...changes);
      toast(`Saved ${changes.length} change${changes.length > 1 ? "s" : ""}. Tell Claude to apply them to the files.`);
    } catch (err) {
      toast(err && err.code === "quota_exceeded" ? "Storage is full: ask Claude to clear the applied edits." : "Could not save. Check your connection and press Save again.");
    }
    refreshCount();
  }
  function applyPending(changes) {        // re-show saved but not yet applied edits after a reload
    const els = editableElements();
    changes.forEach(c => { const el = els.find(e => norm(e.textContent) === c.before); if (el) el.innerHTML = c.afterHtml; });
  }
  $("editToggle").onclick = () => setEditing(!editing);
  $("editSave").onclick = save;
  $("editUndo").onclick = () => { changedList().forEach(([el, o]) => (el.innerHTML = o.html)); refreshCount(); };

  /* ---------- start: only for people who can edit ---------- */
  (async () => {
    if (!window.claude || !window.claude.use) return;
    const user = await window.claude.use("user");
    if (!user || !(await user.canEdit())) return;
    db = await window.claude.use("db");
    if (!db) return;
    ui.hidden = false;
    try {
      const snap = await db.collection("edits").where("status", "==", "pending").get();
      pending = snap.docs.flatMap(d => (d.data().changes || []));
      if (pending.length) setTimeout(() => { applyPending(pending); refreshCount(); }, 600);
    } catch (e) { /* page still works without the saved list */ }
    refreshCount();
  })();
})();
